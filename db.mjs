import pg from 'pg';
import { AsyncLocalStorage } from 'node:async_hooks';
import { randomBytes, scryptSync } from 'node:crypto';
const { Pool } = pg;
const context = new AsyncLocalStorage();
let pool, initialized;
function getPool() {
  if (!pool) {
    const connectionString = process.env.NETLIFY_DB_URL || process.env.DATABASE_URL;
    if (!connectionString) throw new Error('Missing PostgreSQL connection: create Netlify Database or set DATABASE_URL.');
    pool = new Pool({ connectionString, max: 3, connectionTimeoutMillis: 6000, idleTimeoutMillis: 10000, allowExitOnIdle: true, statement_timeout: 12000 });
    pool.on('error', () => console.error('Idle PostgreSQL connection lost.'));
  }
  return pool;
}
// Original SQL uses positional ? placeholders; all values remain bound parameters.
export function parameters(sql) {
  let index=0;
  return sql.replace(/\?/g, () => '$'+(++index));
}
async function query(sql, values) {
  const executor = context.getStore() || getPool();
  return executor.query(parameters(sql), values);
}
export async function all(sql,...values) { return (await query(sql,values)).rows; }
export async function one(sql,...values) { return (await query(sql,values)).rows[0]; }
export async function run(sql,...values) {
  const result=await query(sql,values);
  return {changes:result.rowCount,lastInsertRowid:result.rows[0]?.id};
}
// Serialize workflow transitions across all function instances, including slot claims,
// disputes and payment records. The lock is released automatically on commit/rollback.
export async function tx(fn) {
  const client=await getPool().connect();
  try {
    await client.query('BEGIN');
    await client.query("SET LOCAL lock_timeout = '5s'");
    await client.query('SELECT pg_advisory_xact_lock(73194651)');
    const result=await context.run(client,fn);
    await client.query('COMMIT');
    return result;
  } catch(error) {
    try { await client.query('ROLLBACK'); } catch {}
    throw error;
  } finally { client.release(); }
}
const schema = "CREATE TABLE IF NOT EXISTS users(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,email TEXT UNIQUE NOT NULL,password TEXT NOT NULL,admin INTEGER NOT NULL DEFAULT 0,created TEXT DEFAULT (CURRENT_TIMESTAMP::text));\nCREATE TABLE IF NOT EXISTS sessions(id TEXT PRIMARY KEY,uid INTEGER REFERENCES users(id),csrf TEXT NOT NULL,expires BIGINT NOT NULL);\nCREATE TABLE IF NOT EXISTS tasks(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,owner INTEGER NOT NULL REFERENCES users(id),title TEXT NOT NULL,category TEXT NOT NULL,description TEXT NOT NULL,proof TEXT NOT NULL,reward INTEGER NOT NULL CHECK(reward>=10000),slots INTEGER NOT NULL CHECK(slots BETWEEN 1 AND 100),minutes INTEGER NOT NULL,deadline TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'pending',fundref TEXT UNIQUE,created TEXT DEFAULT (CURRENT_TIMESTAMP::text));\nCREATE TABLE IF NOT EXISTS applications(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,task INTEGER NOT NULL REFERENCES tasks(id),worker INTEGER NOT NULL REFERENCES users(id),status TEXT NOT NULL DEFAULT 'claimed',proof TEXT,reason TEXT,dispute TEXT,payout TEXT NOT NULL DEFAULT 'none',payref TEXT UNIQUE,created TEXT DEFAULT (CURRENT_TIMESTAMP::text),UNIQUE(task,worker));\nCREATE TABLE IF NOT EXISTS reports(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,task INTEGER REFERENCES tasks(id),reporter INTEGER REFERENCES users(id),reason TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'open',created TEXT DEFAULT (CURRENT_TIMESTAMP::text));\nCREATE TABLE IF NOT EXISTS audit(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor INTEGER REFERENCES users(id),action TEXT NOT NULL,target INTEGER,detail TEXT,created TEXT DEFAULT (CURRENT_TIMESTAMP::text));\nCREATE INDEX IF NOT EXISTS tasks_status ON tasks(status,deadline); CREATE INDEX IF NOT EXISTS apps_worker ON applications(worker,status);\nCREATE TABLE IF NOT EXISTS rate_limits(key TEXT PRIMARY KEY, hits INTEGER NOT NULL, expires BIGINT NOT NULL);\nCREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires);\nCREATE INDEX IF NOT EXISTS rate_limits_expiry ON rate_limits(expires);\n";
async function initialize() {
  await tx(async () => {
    const client=context.getStore();
    await client.query(schema);
    if (process.env.ADMIN_EMAIL && process.env.ADMIN_PASSWORD) {
      const email=process.env.ADMIN_EMAIL.trim().toLowerCase();
      if (process.env.ADMIN_PASSWORD.length < 14) throw new Error('ADMIN_PASSWORD must be at least 14 characters.');
      const existing=await one('SELECT admin FROM users WHERE email=?',email);
      if (existing && !existing.admin) throw new Error('Admin bootstrap email is already a non-admin account.');
      if (!existing) {
        const salt=randomBytes(16).toString('hex');
        const password=salt+':'+scryptSync(process.env.ADMIN_PASSWORD,salt,64).toString('hex');
        await run('INSERT INTO users(name,email,password,admin) VALUES(?,?,?,1) ON CONFLICT(email) DO NOTHING','HustleNG Admin',email,password);
        const created=await one('SELECT admin FROM users WHERE email=?',email);
        if(!created?.admin) throw new Error('Admin account could not be safely provisioned.');
      }
    }
    await run('DELETE FROM sessions WHERE expires<?',Date.now());
    await run('DELETE FROM rate_limits WHERE expires<?',Date.now());
  });
}
export function ready() {
  if (!initialized) initialized=initialize().catch(error=>{initialized=undefined;throw error});
  return initialized;
}
